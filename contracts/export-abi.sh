#!/usr/bin/env bash
# Copies compiled ABIs into the frontend, backend and agent after `forge build`.
set -euo pipefail
cd "$(dirname "$0")"
node -e '
const fs=require("fs");
const read=(n)=>JSON.parse(fs.readFileSync(`out/${n}.sol/${n}.json`,"utf8")).abi;
for (const [name, js] of [["SkillPay","skillPayAbi"],["SkillPayEscrow","escrowAbi"]]) {
  const abi=read(name);
  fs.writeFileSync(`../frontend/src/contracts/${js}.js`,`// Auto-generated by contracts/export-abi.sh. Do not edit.\nexport const ${js} = `+JSON.stringify(abi,null,2)+"\n");
  fs.writeFileSync(`../backend/src/contracts/${js}.json`,JSON.stringify(abi,null,2)+"\n");
}
fs.mkdirSync("../agent/src/contracts",{recursive:true});
fs.writeFileSync("../agent/src/contracts/escrowAbi.json",JSON.stringify(read("SkillPayEscrow"),null,2)+"\n");
console.log("ABIs exported");'
