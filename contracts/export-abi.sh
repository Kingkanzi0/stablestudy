#!/usr/bin/env bash
# Copies the compiled SkillPay ABI into the frontend and backend after `forge build`.
set -euo pipefail
cd "$(dirname "$0")"
node -e '
const fs=require("fs");
const abi=JSON.parse(fs.readFileSync("out/SkillPay.sol/SkillPay.json","utf8")).abi;
fs.writeFileSync("../frontend/src/contracts/skillPayAbi.js","// Auto-generated by contracts/export-abi.sh. Do not edit.\nexport const skillPayAbi = "+JSON.stringify(abi,null,2)+"\n");
fs.writeFileSync("../backend/src/contracts/skillPayAbi.json",JSON.stringify(abi,null,2)+"\n");
console.log("ABI exported");'
